"""Build signup.js from the approved staging site (Katelyn, 2026-11-20 list, edits through 11-24).
Run: python tools/build_signup.py <staging.json>   (staging.json from the page scrape)."""
import json, re, sys, difflib
S = json.load(open(sys.argv[1], encoding="utf-8"))
src = open("data.js", encoding="utf-8").read()
old = {m[0]: m[2] for m in re.findall(r"id: '([^']+)', name: ([\"'])(.*?)\2", src)}
def norm(s): return re.sub(r"[^a-z0-9]+", " ", s.lower().replace("&", " and ")).replace(" the ", " ").strip()
ALIAS = {"food-works":"foodworks","anthonys-seafood":"anthonys","benjamins-raw-bar":"benjamins","the-food-shack":"food-shack","brick-alley-pub":"brick-alley"}
idmap = {}
for r in S:
    sl = r["slug"]; hit = None
    if sl in old: hit = sl
    elif ALIAS.get(sl) in old: hit = ALIAS[sl]
    else:
        for i, n in old.items():
            if norm(n) == norm(r["title"]): hit = i
        if not hit:
            m = difflib.get_close_matches(norm(r["title"]), [norm(n) for n in old.values()], 1, 0.8)
            for i, n in old.items():
                if m and norm(n) == m[0]: hit = i
    idmap[sl] = hit
for sl, h in idmap.items(): print("  ", sl, "->", h)
new = [r["slug"] for r in S if not idmap[r["slug"]]]
gone = [i for i in old if i not in set(idmap.values())]
print("matched", len(S) - len(new), "new", new, "removed", [(i, old[i]) for i in gone])
out = {}
for r in S:
    rid = idmap[r["slug"]] or r["slug"]
    e = {"name": r["title"]}
    if r.get("address"): e["address"] = r["address"]
    if r.get("phone"): e["phone"] = r["phone"]
    if r.get("web"): e["url"] = r["web"]
    if r.get("bio"): e["bio"] = r["bio"]
    e["offer"] = {k: sorted(set(r["offer"].get(k, []))) for k in ("breakfast", "lunch", "dinner")}
    if "brunch" in r["offer"]:
        e["offer"]["breakfast"] = sorted(set(e["offer"]["breakfast"]) | set(r["offer"]["brunch"]))
    bo = r.get("blackout") or ""; ru = r.get("rules") or ""
    e["blackout"] = "" if re.match(r"No additional", bo) else bo
    e["rules"] = "" if re.match(r"No additional", ru) else ru
    e["isNew"] = rid not in old
    out[rid] = e
js = "// Restaurant details from the approved 2026-27 Dinner Club website pages (Katelyn's 11-20 list, edits through 11-24).\n// Merged LAST, so these values win over info.js. Restaurants not already in RESTAURANTS are appended.\n// Generated by tools/build_signup.py - do not hand-edit.\nconst SIGNUP = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\nconst SIGNUP_IDS = " + json.dumps(list(out)) + ";\n"
js += """(function(){
  RESTAURANTS.forEach(function(r){ var s = SIGNUP[r.id]; if (s) { Object.keys(s).forEach(function(k){ if (k !== 'isNew') r[k] = s[k]; }); if (!s.blackout) delete r.blackout; if (!s.rules) delete r.rules; if (s.status) {} } });
  Object.keys(SIGNUP).forEach(function(id){ if (!RESTAURANTS.some(function(r){ return r.id === id; })) { var s = SIGNUP[id], r = { id: id }; Object.keys(s).forEach(function(k){ if (k !== 'isNew') r[k] = s[k]; }); RESTAURANTS.push(r); } });
  for (var i = RESTAURANTS.length - 1; i >= 0; i--) if (SIGNUP_IDS.indexOf(RESTAURANTS[i].id) < 0) RESTAURANTS.splice(i, 1);
})();
"""
open("signup.js", "w", encoding="utf-8").write(js)
